"""Leased immutable native archives; this module never touches native objects.

Recovery may publish an accepted archive into this cache after its GUI-thread
capture. Preview readers pin that file until their owned process has exited.
The cache is an optimization, never the durable recovery/save authority.
"""
from dataclasses import dataclass
from pathlib import Path
import shutil
import threading
import uuid


@dataclass(frozen=True)
class SnapshotKey:
    instance_id: str
    revision: str
    generation: int
    serial: int
    policy: str = "accepted-recovery-v1"


def _identity(path):
    stat = path.stat()
    return stat.st_dev, stat.st_ino, stat.st_size, stat.st_mtime_ns


class SnapshotLease:
    def __init__(self, store, record):
        self.path = record["path"]
        self.key = record["key"]
        self._store, self._record = store, record

    @property
    def file_identity(self):
        with self._store._lock:
            if self._record is None:
                raise RuntimeError("Snapshot lease has been released")
            return self._record["identity"]

    def release(self):
        self._store._release(self)


class SnapshotStore:
    def __init__(self, directory):
        self.directory = Path(directory)
        self._lock = threading.RLock()
        self._current = {}
        self._retired = set()
        self.closed = False
        self.hits = self.published = 0

    @staticmethod
    def _delete(record):
        # Only files generated by this store are removed. A Windows file lock
        # may delay cleanup; never fail a successful native task for that.
        try:
            record["path"].unlink(missing_ok=True)
        except OSError:
            pass

    def _retire(self, record):
        record["retired"] = True
        if record["pins"] == 0:
            self._delete(record)

    def publish(self, key, source):
        """File-worker only. Source must stay immutable during publication."""
        with self._lock:
            if self.closed or key.instance_id in self._retired:
                return False
        self.directory.mkdir(parents=True, exist_ok=True)
        target = self.directory / ("snapshot-" + uuid.uuid4().hex + ".FCStd")
        source = Path(source)
        before = _identity(source)
        try:
            # Run only on the file worker for background recovery. Independent
            # ownership prevents a faulty preview writer from damaging the
            # durable recovery pair through a hard-link alias.
            shutil.copyfile(source, target)
            if _identity(source) != before:
                raise RuntimeError("Snapshot source changed during publication")
            record = {"key": key, "path": target, "identity": _identity(target),
                      "pins": 0, "retired": False}
            with self._lock:
                if self.closed or key.instance_id in self._retired:
                    self._delete(record)
                    return False
                previous = self._current.get(key.instance_id)
                # An older publisher cannot replace a newer retained state.
                if previous and previous["key"].serial > key.serial:
                    self._delete(record)
                    return False
                self._current[key.instance_id] = record
                self.published += 1
                if previous:
                    self._retire(previous)
            return True
        except BaseException:
            try:
                target.unlink(missing_ok=True)
            except OSError:
                pass
            raise

    def try_acquire(self, key):
        with self._lock:
            if key is None:
                return None
            record = self._current.get(key.instance_id)
            if self.closed or record is None or record["key"] != key:
                return None
            try:
                unchanged = _identity(record["path"]) == record["identity"]
            except OSError:
                unchanged = False
            if not unchanged:
                self._current.pop(key.instance_id, None)
                self._retire(record)
                return None
            record["pins"] += 1
            self.hits += 1
            return SnapshotLease(self, record)

    def _release(self, lease):
        with self._lock:
            record, lease._record = lease._record, None
            if record is None:
                return
            record["pins"] -= 1
            if record["retired"] and record["pins"] == 0:
                self._delete(record)

    def retire_document(self, instance_id):
        with self._lock:
            self._retired.add(instance_id)
            record = self._current.pop(instance_id, None)
            if record:
                self._retire(record)

    def close(self):
        with self._lock:
            self.closed = True
            for record in self._current.values():
                self._retire(record)
            self._current.clear()
